function whoWonMatch(turn1: string, turn2: string) {
    if (!VALID_TURNS.includes(turn1) || !VALID_TURNS.includes(turn2)){
        return 0;
    }

    // Rest of function was generated by Gemini 3.6 Flash
    if (turn1 === turn2) return 0;
    if (turn1 === "error") return 2;
    if (turn2 === "error") return 1;

    const WINNING_MOVES: Record<string, string> = {
        "KAMEN": "NOZNICE",
        "PAPIER": "KAMEN",
        "NOZNICE": "PAPIER"
    };

    return WINNING_MOVES[turn1] === turn2 ? 1 : 2;
}

