function animateTurn(turn?: number, countDownTickTime?: number) {
    function setBothTurnResultElementsTo(text: string) {
        CURRENT_TURN_RESULT_TEXT_ELEMENTS.forEach(
            (element) => {
                if (!element) {return;}
                element.textContent = text;
            }
        )
    }
    if (!turn) { turn = CURRENT_TURN + 1}
    if (turn < 0 || turn >= GAME_TURNS.length) { return; }
    if (!countDownTickTime) {countDownTickTime = 1000}
    
    if (!CURRENT_TURN_ELEMENTS[0] || !CURRENT_TURN_ELEMENTS[1]) { console.error(`Current turn elements not loaded.`); return; }
    if (!CURRENT_TURN_RESULT_TEXT_ELEMENTS[0] || !CURRENT_TURN_RESULT_TEXT_ELEMENTS[1]) { console.error(`Current turn elements not loaded.`); return; }
    
    const uuid = crypto.randomUUID();
    CURRENT_ANIMATION_UUID = uuid;
    changeTurn(CURRENT_TURN); // Just in case an animation is already in progress


    CURRENT_TURN_ELEMENTS.forEach(
        (element) => {
            if (!element) {return;}
            element.textContent = "✊";
            element.style.backgroundColor = "#000000";
        }
    )

    // _focusTurnInHistory(turn);
    // ANIMATING_TOWARDS_TURN = turn;
    // _unfocusTurnInHistory(CURRENT_TURN);

    // Countdown from 3 to 0
    for (let i = 0; i < 4; i++) {
        setTimeout(
            (animation_uuid: string) => {
                if (CURRENT_ANIMATION_UUID != animation_uuid) {console.log(`Changed turn before finishing animation, ignoring animation`); return;}
                setBothTurnResultElementsTo((3 - i).toString())
            },
            i * countDownTickTime,
            uuid
        )
    }
    setTimeout(
        (expected_uuid: string) => {
            if (CURRENT_ANIMATION_UUID != expected_uuid) {console.log(`Changed turn before finishing animation, ignoring animation`); return;}
            changeTurn(turn);
            // ANIMATING_TOWARDS_TURN = null;
        },
        3 * countDownTickTime,
        uuid
    )
    
}

function _animationNextTurn() {
    if (ANIMATION_IS_PAUSED) { return; }
    animateTurn(CURRENT_TURN+1, 1000 * ANIMATION_SPEED)
    if (CURRENT_TURN + 1 >= GAME_TURNS.length) {
        document.getElementById("pause_button")!.textContent = "Play";
        return;
    }
    setTimeout(_animationNextTurn, (3000 + WAIT_BETWEEN_TURN_ANIMATION) * ANIMATION_SPEED)
}

function startAnimation() {
    if (CURRENT_TURN + 1 >= GAME_TURNS.length) {
        return;
    }
    document.getElementById("pause_button")!.textContent = "Pause";
    ANIMATION_IS_PAUSED = false;
    _animationNextTurn()
}

function pauseButtonPress(){
    if (CURRENT_TURN + 1 >= GAME_TURNS.length && ANIMATION_IS_PAUSED) {
        CURRENT_TURN = 0;
        startAnimation();
        return;
    }
    if (ANIMATION_IS_PAUSED){
        startAnimation();
    } else {
        cancelCurrentAnimation(true);
    }
}

function setReplaySpeed(speed: number) {
    console.log(`changiong speed: ${speed}`)
    if (speed < 0.1) { alert(`Replay speed ${speed} is too small. Only values >= 0.1 are allowed`)}
    const round_decimal_places = 3
    ANIMATION_SPEED = Math.round(speed * (10**round_decimal_places)) / 10**round_decimal_places;
    // @ts-ignore
    if (document.getElementById("replay_speed_input").value == speed.toString()) {
        // This function is called on input => prevent recursive calls
        return;
    }
    // @ts-ignore
    document.getElementById("replay_speed_input").value = speed.toString();
}
